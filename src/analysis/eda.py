"""DVC stage `eda`: exploratory data analysis of the filings, labels and features.

Writes a Markdown report with tables and figures to reports/eda/, plus headline numbers to
reports/eda_metrics.json. Everything is computed from the pipeline outputs, so the report is
regenerated by `dvc repro` whenever the data changes and always matches the current dataset.

Run:  python -m src.analysis.eda
"""

import json
import logging
from pathlib import Path
from typing import Dict, List

import matplotlib

matplotlib.use("Agg")  # no display needed
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from src.common.config import load_params, setup_logging  # noqa: E402
from src.features.columns import FEATURE_COLUMNS  # noqa: E402

logger = logging.getLogger(__name__)
logging.getLogger("matplotlib").setLevel(logging.WARNING)

MANIFEST = Path("data/raw/manifest.csv")
PARSED_DIR = Path("data/parsed")
LABELS = Path("data/labels/labels.csv")
FEATURES = Path("data/features/features.csv")
PARSE_FAILURES = Path("reports/parse_failures.csv")
OUT_DIR = Path("reports/eda")
METRICS = Path("reports/eda_metrics.json")

FEATURE_GROUPS = {
    "neg_ratio": "word share",
    "unc_ratio": "word share",
    "lit_ratio": "word share",
    "pos_ratio": "word share",
    "fk_grade": "readability",
    "avg_sentence_len": "readability",
    "log_risk_words": "length",
    "risk_share": "length",
    "risk_words_change": "year-over-year",
    "tfidf_similarity": "year-over-year",
    "d_neg_ratio": "year-over-year",
    "d_unc_ratio": "year-over-year",
    "d_lit_ratio": "year-over-year",
    "d_fk_grade": "year-over-year",
}


# ----------------------------------------------------------------------------- loading


def load_parsed(parsed_dir: Path) -> pd.DataFrame:
    """One row per parsed filing with its section and filing lengths (the text itself is not kept)."""
    rows = []
    for path in sorted(parsed_dir.glob("*/*.json")):
        rec = json.loads(path.read_text(encoding="utf-8"))
        rows.append(
            {
                "ticker": rec["ticker"],
                "accession": rec["accession"],
                "filing_date": rec["filing_date"],
                "report_date": rec["report_date"],
                "risk_words": rec["risk_words"],
                "full_words": rec["full_words"],
            }
        )
    df = pd.DataFrame(rows)
    for col in ("filing_date", "report_date"):
        df[col] = pd.to_datetime(df[col])
    return df


def split_masks(df: pd.DataFrame, split: Dict) -> Dict[str, pd.Series]:
    """Same time-based split as training: train ends `embargo_days` before the test period."""
    test_start = pd.Timestamp(split["test_start_date"])
    train_end = test_start - pd.Timedelta(days=int(split["embargo_days"]))
    dates = pd.to_datetime(df["filing_date"])
    return {"train": dates <= train_end, "test": dates >= test_start}


# ----------------------------------------------------------------------------- analysis


def coverage_table(parsed: pd.DataFrame) -> pd.DataFrame:
    """Filings per company and fiscal year (year of the period end)."""
    table = pd.crosstab(parsed["ticker"], parsed["report_date"].dt.year)
    table.columns = [str(c) for c in table.columns]
    return table


def count_gaps(table: pd.DataFrame) -> int:
    """Missing years between a company's first and last filing (not before or after its run)."""
    gaps = 0
    for row in table.values:
        present = np.flatnonzero(row)
        if len(present):
            gaps += int((row[present[0] : present[-1] + 1] == 0).sum())
    return gaps


def plural(n: int, word: str, many: str = "") -> str:
    return f"{n} {word}" if n == 1 else f"{n} {many or word + 's'}"


def feature_summary(features: pd.DataFrame) -> pd.DataFrame:
    usable = features[features["has_prior"]]
    out = pd.DataFrame(
        {
            "group": [FEATURE_GROUPS.get(c, "") for c in FEATURE_COLUMNS],
            "missing_%": [100 * usable[c].isna().mean() for c in FEATURE_COLUMNS],
            "mean": [usable[c].mean() for c in FEATURE_COLUMNS],
            "std": [usable[c].std() for c in FEATURE_COLUMNS],
            "min": [usable[c].min() for c in FEATURE_COLUMNS],
            "median": [usable[c].median() for c in FEATURE_COLUMNS],
            "max": [usable[c].max() for c in FEATURE_COLUMNS],
            "outliers_%": [100 * iqr_outlier_share(usable[c]) for c in FEATURE_COLUMNS],
        },
        index=FEATURE_COLUMNS,
    )
    return out


def iqr_outlier_share(values: pd.Series) -> float:
    """Share of values outside 1.5 interquartile ranges of the quartiles."""
    v = values.dropna()
    if v.empty:
        return 0.0
    q1, q3 = v.quantile([0.25, 0.75])
    spread = q3 - q1
    return float(((v < q1 - 1.5 * spread) | (v > q3 + 1.5 * spread)).mean())


def label_correlations(train: pd.DataFrame) -> pd.DataFrame:
    """Correlation of each feature with the binary target on the training period only."""
    n = len(train)
    corr = [train[c].corr(train["target"]) for c in FEATURE_COLUMNS]
    out = pd.DataFrame({"correlation": corr}, index=FEATURE_COLUMNS)
    out["abs"] = out["correlation"].abs()
    out.attrs["noise_band"] = 1.96 / np.sqrt(n) if n > 3 else float("nan")
    return out.sort_values("abs", ascending=False)


def train_test_shift(train: pd.DataFrame, test: pd.DataFrame) -> pd.Series:
    """Standardised mean difference (test minus train, in training standard deviations)."""
    shift = {}
    for c in FEATURE_COLUMNS:
        sd = train[c].std()
        shift[c] = (test[c].mean() - train[c].mean()) / sd if sd and not np.isnan(sd) else 0.0
    return pd.Series(shift).sort_values(key=np.abs, ascending=False)


# ----------------------------------------------------------------------------- figures


def save(fig, name: str) -> str:
    fig.tight_layout()
    fig.savefig(OUT_DIR / name, dpi=120)
    plt.close(fig)
    return name


def fig_coverage(table: pd.DataFrame) -> str:
    fig, ax = plt.subplots(figsize=(7, max(6, 0.18 * len(table))))
    ax.imshow(table.values, aspect="auto", cmap="Blues", vmin=0, vmax=max(2, table.values.max()))
    ax.set_xticks(range(len(table.columns)), table.columns)
    ax.set_yticks(range(len(table.index)), table.index, fontsize=7)
    for (i, j), v in np.ndenumerate(table.values):
        if v != 1:
            ax.text(j, i, str(v), ha="center", va="center", fontsize=7, color="crimson" if v == 0 else "white")
    ax.set_xlabel("Fiscal year (period end)")
    ax.set_title("10-K filings per company and fiscal year (0 = missing)")
    return save(fig, "coverage.png")


def fig_labels(labels: pd.DataFrame) -> str:
    lab = labels[labels["labeled"]]
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.8))
    axes[0].hist(lab["abnormal_ret"] * 100, bins=30, color="#4C72B0")
    axes[0].axvline(0, color="black", linewidth=1)
    axes[0].set_xlabel("30-trading-day abnormal return (%)")
    axes[0].set_ylabel("Filings")
    axes[0].set_title("Abnormal return after filing")
    by_year = lab.groupby(pd.to_datetime(lab["filing_date"]).dt.year)["target"].agg(["mean", "size"])
    axes[1].bar(by_year.index.astype(str), by_year["mean"] * 100, color="#DD8452")
    axes[1].axhline(lab["target"].mean() * 100, color="black", linestyle="--", linewidth=1, label="overall")
    for x, (rate, size) in enumerate(zip(by_year["mean"], by_year["size"])):
        axes[1].text(x, rate * 100 + 1, f"n={size}", ha="center", fontsize=8)
    axes[1].set_ylabel("Underperformers (%)")
    axes[1].set_xlabel("Filing year")
    axes[1].set_ylim(0, 100)
    axes[1].set_title("Label balance by filing year")
    axes[1].legend(loc="upper right", fontsize=8)
    return save(fig, "labels.png")


def fig_lengths(parsed: pd.DataFrame) -> str:
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.8))
    axes[0].hist(np.log10(parsed["risk_words"]), bins=30, color="#55A868")
    axes[0].set_xlabel("Risk-factors section length (log10 words)")
    axes[0].set_ylabel("Filings")
    axes[0].set_title("Item 1A length")
    axes[1].hist(100 * parsed["risk_words"] / parsed["full_words"], bins=30, color="#8172B3")
    axes[1].set_xlabel("Risk section share of whole filing (%)")
    axes[1].set_title("Item 1A share of the 10-K")
    return save(fig, "lengths.png")


def fig_correlations(usable: pd.DataFrame) -> str:
    corr = usable[FEATURE_COLUMNS].corr()
    fig, ax = plt.subplots(figsize=(7.5, 6.5))
    im = ax.imshow(corr.values, cmap="RdBu_r", vmin=-1, vmax=1)
    ax.set_xticks(range(len(FEATURE_COLUMNS)), FEATURE_COLUMNS, rotation=90, fontsize=8)
    ax.set_yticks(range(len(FEATURE_COLUMNS)), FEATURE_COLUMNS, fontsize=8)
    for (i, j), v in np.ndenumerate(corr.values):
        if i != j and abs(v) >= 0.5:
            ax.text(j, i, f"{v:.2f}", ha="center", va="center", fontsize=6)
    fig.colorbar(im, ax=ax, shrink=0.8)
    ax.set_title("Correlation between features (|r| >= 0.5 annotated)")
    return save(fig, "feature_correlations.png")


def fig_label_corr(lc: pd.DataFrame) -> str:
    band = lc.attrs["noise_band"]
    ordered = lc.sort_values("correlation")
    fig, ax = plt.subplots(figsize=(7, 4.5))
    ax.barh(ordered.index, ordered["correlation"], color="#4C72B0")
    ax.axvspan(-band, band, color="grey", alpha=0.2, label=f"±{band:.2f}: indistinguishable from 0 (95%)")
    ax.axvline(0, color="black", linewidth=1)
    ax.set_xlabel("Correlation with target (training period)")
    ax.set_title("Each feature against the label")
    ax.legend(loc="lower right", fontsize=8)
    return save(fig, "label_correlations.png")


def fig_shift(shift: pd.Series) -> str:
    ordered = shift.sort_values()
    fig, ax = plt.subplots(figsize=(7, 4.5))
    colors = ["#C44E52" if abs(v) >= 0.5 else "#4C72B0" for v in ordered]
    ax.barh(ordered.index, ordered.values, color=colors)
    ax.axvline(0, color="black", linewidth=1)
    for x in (-0.5, 0.5):
        ax.axvline(x, color="grey", linestyle="--", linewidth=1)
    ax.set_xlabel("Test mean minus train mean (training standard deviations)")
    ax.set_title("Train vs test period shift (red: at least 0.5 sd)")
    return save(fig, "train_test_shift.png")


# ----------------------------------------------------------------------------- report


def md_table(df: pd.DataFrame, floatfmt: str = "{:.4g}") -> str:
    cols = [df.index.name or ""] + [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for idx, row in df.iterrows():
        cells = [floatfmt.format(v) if isinstance(v, (float, np.floating)) else str(v) for v in row]
        lines.append("| " + " | ".join([str(idx)] + cells) + " |")
    return "\n".join(lines)


def build_report(
    manifest: pd.DataFrame,
    parsed: pd.DataFrame,
    labels: pd.DataFrame,
    features: pd.DataFrame,
    failures: pd.DataFrame,
    split: Dict,
) -> Dict:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    data = features.merge(labels[["accession", "labeled", "target", "abnormal_ret"]], on="accession", how="left")
    usable = data[data["has_prior"]]
    modelling = usable[usable["labeled"].fillna(False).astype(bool)]
    masks = split_masks(modelling, split)
    train, test = modelling[masks["train"]], modelling[masks["test"]]

    cov = coverage_table(parsed)
    per_company = cov.sum(axis=1)
    few = per_company[per_company < 2]
    thin = per_company[per_company < per_company.median() - 1].sort_values()
    gaps = count_gaps(cov)
    status_counts = manifest["status"].fillna("unknown").value_counts()
    summary = feature_summary(features)
    lc = label_correlations(train)
    shift = train_test_shift(train, test)
    corr = usable[FEATURE_COLUMNS].corr().abs()
    pairs = [
        (a, b, corr.loc[a, b])
        for i, a in enumerate(FEATURE_COLUMNS)
        for b in FEATURE_COLUMNS[i + 1 :]
        if corr.loc[a, b] >= 0.7
    ]
    lab = labels[labels["labeled"]]
    band = lc.attrs["noise_band"]
    outside_band = lc[lc["abs"] > band]

    figures = {
        "coverage": fig_coverage(cov),
        "labels": fig_labels(labels),
        "lengths": fig_lengths(parsed),
        "correlations": fig_correlations(usable),
        "label_corr": fig_label_corr(lc),
        "shift": fig_shift(shift),
    }

    metrics = {
        "companies": int(parsed["ticker"].nunique()),
        "filings": int(len(parsed)),
        "companies_with_fewer_than_2_filings": int(len(few)),
        "companies_with_few_filings": int(len(thin)),
        "coverage_gaps": gaps,
        "parse_failures": int(len(failures)),
        "labeled": int(len(lab)),
        "positive_rate": round(float(lab["target"].mean()), 4),
        "with_prior": int(features["has_prior"].sum()),
        "n_train": int(len(train)),
        "n_test": int(len(test)),
        "max_abs_label_correlation": round(float(lc["abs"].max()), 4),
        "label_noise_band": round(float(band), 4),
        "features_outside_noise_band": int(len(outside_band)),
        "max_abs_train_test_shift_sd": round(float(shift.abs().max()), 3),
        "highly_correlated_feature_pairs": len(pairs),
    }

    top = lc.iloc[0]
    lines: List[str] = [
        "# FilingLens: Exploratory Data Analysis",
        "",
        "Generated by the DVC stage `eda` (`python -m src.analysis.eda`) from the current pipeline outputs. "
        "Do not edit by hand: rerun `dvc repro eda` instead.",
        "",
        "## 1. Key findings",
        "",
        f"- **Coverage.** {metrics['filings']} filings from {metrics['companies']} companies. "
        f"{plural(len(few), 'company', 'companies')} with fewer than two filings "
        "(no year-over-year comparison possible)"
        + (f": {', '.join(few.index)}" if len(few) else "")
        + f"; {plural(gaps, 'missing year')} between a company's first and last filing.",
        f"- **Quality.** Parse failures: {metrics['parse_failures']}. Manifest statuses: "
        + ", ".join(f"{k} {v}" for k, v in status_counts.items())
        + ".",
        f"- **Label balance.** {metrics['labeled']} filings are labeled; {100 * metrics['positive_rate']:.1f}% "
        "underperformed the benchmark, so the classes are balanced and accuracy against the majority class is a "
        "fair baseline.",
        f"- **Modelling sample.** {metrics['with_prior']} filings have a prior-year filing; after the time split and "
        f"embargo, {metrics['n_train']} are used for training and {metrics['n_test']} for testing.",
        f"- **Signal.** The strongest single feature-label correlation in the training period is "
        f"{top['correlation']:+.3f} (`{lc.index[0]}`). With {metrics['n_train']} training filings, correlations "
        f"inside ±{band:.3f} cannot be told apart from zero at the 95% level; {len(outside_band)} of "
        f"{len(FEATURE_COLUMNS)} features fall outside it, about what chance alone would produce across "
        f"{len(FEATURE_COLUMNS)} tests. This anticipates the model result: weak or no detectable signal.",
        f"- **Redundancy.** {plural(len(pairs), 'feature pair')} with |correlation| of at least 0.7"
        + (": " + "; ".join(f"`{a}`/`{b}` {r:.2f}" for a, b, r in pairs) if pairs else "")
        + ". The models use regularisation (logistic regression) and shallow trees (XGBoost), which tolerate this.",
        f"- **Train vs test.** The largest shift between periods is {shift.iloc[0]:+.2f} training standard "
        f"deviations (`{shift.index[0]}`). Shifts are tracked formally by the `drift` stage (PSI and KS test).",
        "",
        "## 2. Coverage and data quality",
        "",
        f"![Coverage]({figures['coverage']})",
        "",
        "Filings per company and fiscal year (year of the period end). Because the download window is defined by "
        "filing date, the first column only holds reports filed after the window opened, and the last column only "
        "companies whose latest fiscal year has already ended. A 2 usually means a 52/53-week fiscal year that ended "
        "in the first days of January, putting two period ends in one calendar year. Missing years in the middle of "
        "the chart, or a company with far fewer filings than the others, point to a download problem.",
        "",
        "| Check | Result |",
        "|---|---|",
        f"| Companies | {metrics['companies']} |",
        f"| Filings parsed | {metrics['filings']} |",
        f"| Companies with fewer than 2 filings | {len(few)}"
        + (f" ({', '.join(few.index)})" if len(few) else "")
        + " |",
        f"| Companies with far fewer filings than the median ({per_company.median():.0f}) | "
        + (", ".join(f"{t} ({n})" for t, n in thin.items()) if len(thin) else "none")
        + " |",
        f"| Missing years between a company's first and last filing | {gaps} |",
        f"| Parse failures | {metrics['parse_failures']} |",
        f"| Filings without a label yet | {int((~labels['labeled']).sum())} |",
        f"| Filings without a prior-year filing | {int((~features['has_prior']).sum())} |",
        "",
        "## 3. Label",
        "",
        f"![Labels]({figures['labels']})",
        "",
        f"Abnormal return: mean {100 * lab['abnormal_ret'].mean():+.2f}%, "
        f"median {100 * lab['abnormal_ret'].median():+.2f}%, "
        f"standard deviation {100 * lab['abnormal_ret'].std():.2f}%. The target is 1 when the abnormal return is "
        "negative. Returns over 30 trading days are dominated by market noise, which is why a weak model result is "
        "expected.",
        "",
        "## 4. Risk-section text",
        "",
        f"![Lengths]({figures['lengths']})",
        "",
        f"Item 1A length: median {int(parsed['risk_words'].median()):,} words "
        f"(range {int(parsed['risk_words'].min()):,} to {int(parsed['risk_words'].max()):,}); "
        f"median share of the whole filing {100 * (parsed['risk_words'] / parsed['full_words']).median():.1f}%. "
        "Lengths are right-skewed, which is why the model uses the logarithm of the word count.",
        "",
        "## 5. Features",
        "",
        "Summary over filings with a prior-year filing (the rows used for modelling). `outliers_%` counts values "
        "beyond 1.5 interquartile ranges; they are kept, because large changes are exactly what the application "
        "highlights.",
        "",
        md_table(summary.round(4)),
        "",
        f"![Feature correlations]({figures['correlations']})",
        "",
        "## 6. Features against the label",
        "",
        f"![Label correlations]({figures['label_corr']})",
        "",
        md_table(lc[["correlation"]].round(4)),
        "",
        "## 7. Training period against test period",
        "",
        f"![Train-test shift]({figures['shift']})",
        "",
        md_table(shift.round(3).to_frame("shift_sd")),
        "",
    ]
    (OUT_DIR / "eda.md").write_text("\n".join(lines), encoding="utf-8")
    return metrics


def main() -> None:
    setup_logging("eda")
    params = load_params()
    manifest = pd.read_csv(MANIFEST)
    parsed = load_parsed(PARSED_DIR)
    labels = pd.read_csv(LABELS)
    labels["labeled"] = labels["labeled"].astype(bool)
    features = pd.read_csv(FEATURES)
    features["has_prior"] = features["has_prior"].astype(bool)
    failures = pd.read_csv(PARSE_FAILURES)
    metrics = build_report(manifest, parsed, labels, features, failures, params["split"])
    METRICS.write_text(json.dumps(metrics, indent=2))
    logger.info("EDA written to %s: %s", OUT_DIR, metrics)


if __name__ == "__main__":
    main()
